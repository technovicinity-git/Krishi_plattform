// Copies the website's status/stage/purpose labels into the app so both use
// the same words. Run from mobile/:  node tool/sync_labels.mjs
import { readFileSync, writeFileSync } from "node:fs";

const SOURCES = {
  stage: (m) => m.app.stage,
  status: (m) => m.app.status,
  purpose: (m) => m.app.purpose,
  saleStatus: (m) => m.app.saleStatus,
  animalStatus: (m) => m.app.animals.status,
  recordKind: (m) => m.app.animals.kind,
  deathCause: (m) => m.app.animals.causes,
  walletType: (m) => m.app.wallet.type,
  withdrawalStatus: (m) => m.app.wallet.status,
};

const out = {};
for (const locale of ["en", "bn"]) {
  const messages = JSON.parse(readFileSync(`../web/src/messages/${locale}.json`, "utf8"));
  out[locale] = {};
  for (const [group, pick] of Object.entries(SOURCES)) {
    for (const [key, value] of Object.entries(pick(messages))) out[locale][`${group}.${key}`] = value;
  }
}

const dart = (o) =>
  Object.entries(o)
    .map(([k, v]) => `    ${JSON.stringify(k)}: ${JSON.stringify(v).replace(/\$/g, "\$")},`)
    .join("\n");

writeFileSync(
  "lib/l10n/labels.g.dart",
  `// GENERATED by tool/sync_labels.mjs from web/src/messages. Do not edit.\n\nconst Map<String, Map<String, String>> kLabels = {\n  "en": {\n${dart(out.en)}\n  },\n  "bn": {\n${dart(out.bn)}\n  },\n};\n`,
);
console.log(`wrote ${Object.keys(out.en).length} labels`);
